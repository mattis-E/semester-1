fruit = ["cherry", "strawberry", "melon", "grape", "apple"]

# Sort list
fruit.sort()
print(f"Alphabetically sorted: {fruit}")

# Reverse order of list items
fruit.sort(reverse = True)
print(f"Sorted reverse-alphabetically: {fruit}")

# Remove all items
fruit.clear()
print(f"Cleared list: {fruit.clear()}")